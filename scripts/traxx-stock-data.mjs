/*
  Generates src/core/traxx/stock-data.ts from Traxx's built-in resources (Traxx/res and
  Traxx/Standard in Traxx_OnGoing_Updates), so core code can use them in workers and tests:

    the sixteen stock MTM2 palettes, in palresid order (TraxxDoc.cpp)
    metalcr2_act3, the palette a texture without its own .ACT is read against
    tpark_fo.bin, the default fog map, run-length coded (AssignDefMTM2Fogmap)
    def_brow.bin and def_icon.bin, the default UI pictures (LoadMTM2Palette)

    node scripts/traxx-stock-data.mjs [path/to/Traxx_OnGoing_Updates]
*/
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { homedir } from "node:os";

const root = join(process.argv[2] ?? join(homedir(), "dev/Traxx_OnGoing_Updates"), "Traxx");
const res = (n) => readFileSync(join(root, "res", n));
const b64 = (buf) => Buffer.from(buf).toString("base64");

// palresid[16], TraxxDoc.cpp, with the names its comments give.
const palettes = [
  ["tpark.act", "Farm Road"], ["main_act.bin", "Voodoo"], ["aztec_ac.bin", "Excavation"], ["junk_act.bin", "Scrapyard"],
  ["alaska_a.bin", "Heights"], ["snake_ac.bin", "Sidewinder"], ["aussie_a.bin", "Tinhorn"], ["baja_act.bin", "Tumbleweed"],
  ["rockqry_.bin", "Breakneck"], ["summit1_.bin", "Arena"], ["summit2_.bin", "Pyramid"], ["summit3_.bin", "Hypercube"],
  ["gravey_a.bin", "Graveyard"], ["c98_act.bin", "C98"], ["war_act.bin", "Torture pit"], ["metalcr3.bin", "Hacked MTM2 version of metalcr2"],
];

const header = readFileSync(join(root, "Standard", "metalcr2_act3.h"), "latin1");
const numbers = header.slice(header.indexOf("{") + 1, header.lastIndexOf("}")).match(/\d+/g).map(Number);
if (numbers.length !== 768) throw new Error(`metalcr2_act3.h: ${numbers.length} values, expected 768`);

/* A TABBED_TABLE: name TAB description, a line each (StockSoundsDlg::OnInitDialog). */
function table(file) {
  return new TextDecoder("latin1").decode(res(file)).split(/\r?\n/).filter((l) => l.includes("\t")).map((l) => l.split("\t").slice(0, 2));
}

const out = `/*
  Traxx's built-in resources, generated by scripts/traxx-stock-data.mjs from Traxx/res and
  Traxx/Standard. Do not edit by hand.
*/

/** The sixteen stock MTM2 palettes (palresid, TraxxDoc.cpp): 768 RGB bytes each, base64. */
export const STOCK_PALETTES_B64: readonly { name: string; data: string }[] = [
${palettes.map(([file, name]) => `  { name: ${JSON.stringify(name)}, data: "${b64(res(file))}" },`).join("\n")}
];

/** metalcr2_act3 (Standard/metalcr2_act3.h), base64. */
export const METALCR2_ACT3_B64 = "${b64(Uint8Array.from(numbers))}";

/** IDR_TPARK_FOGMAP_C (res/tpark_fo.bin): value, run-length pairs expanding to 32768 bytes, base64. */
export const DEFAULT_FOGMAP_RLE_B64 = "${b64(res("tpark_fo.bin"))}";

/** IDR_DEF_BROWSE (res/def_brow.bin): the default track picture, a BMP, base64. */
export const DEFAULT_BROWSE_BMP_B64 = "${b64(res("def_brow.bin"))}";

/** IDR_DEF_ICON (res/def_icon.bin): the default track icon, a BMP, base64. */
export const DEFAULT_ICON_BMP_B64 = "${b64(res("def_icon.bin"))}";

/** IDR_STOCK_SOUNDS (res/stocksnd.txt): the game's impact sounds, name and description. */
export const STOCK_SOUNDS: readonly (readonly [string, string])[] = ${JSON.stringify(table("stocksnd.txt"))};

/** IDR_STOCK_CONTSOUNDS (res/stockcnt.txt): the game's continuous sounds. */
export const STOCK_CONT_SOUNDS: readonly (readonly [string, string])[] = ${JSON.stringify(table("stockcnt.txt"))};
`;
writeFileSync(new URL("../src/core/traxx/stock-data.ts", import.meta.url), out);
console.log("wrote src/core/traxx/stock-data.ts");
